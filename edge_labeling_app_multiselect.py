def compute_boundaries(labels: np.ndarray) -> np.ndarray:
    boundaries = np.zeros(labels.shape, dtype=bool)
    boundaries[:, 1:] |= labels[:, 1:] != labels[:, :-1]
    boundaries[:, :-1] |= labels[:, 1:] != labels[:, :-1]
    boundaries[1:, :] |= labels[1:, :] != labels[:-1, :]
    boundaries[:-1, :] |= labels[1:, :] != labels[:-1, :]
    return boundaries


def overlay_boundaries(image: Image.Image, boundaries: np.ndarray) -> np.ndarray:
    rgb = np.asarray(image.convert("RGB"), dtype=np.uint8).copy()
    rgb[boundaries] = np.array([255, 255, 255], dtype=np.uint8)
    return rgb


def build_adjacency(labels: np.ndarray) -> dict[int, set[int]]:
    adjacency: dict[int, set[int]] = {int(label): set() for label in np.unique(labels)}

    for values_a, values_b in (
        (labels[:, :-1].ravel(), labels[:, 1:].ravel()),
        (labels[:-1, :].ravel(), labels[1:, :].ravel()),
    ):
        different = values_a != values_b
        for node_a, node_b in zip(values_a[different], values_b[different]):
            a = int(node_a)
            b = int(node_b)
            adjacency.setdefault(a, set()).add(b)
            adjacency.setdefault(b, set()).add(a)

    return adjacency


def group_frontier(adjacency: dict[int, set[int]], group_nodes: set[int]) -> set[int]:
    """Return nodes directly adjacent to the group but not inside it."""
    frontier: set[int] = set()
    for node in group_nodes:
        frontier.update(adjacency.get(node, set()))
    return frontier - group_nodes


def is_connected_group(adjacency: dict[int, set[int]], group_nodes: set[int]) -> bool:
    """Check connectivity in the graph induced by ``group_nodes``."""
    if not group_nodes:
        return True
    start = next(iter(group_nodes))
    visited = {start}
    pending = [start]
    while pending:
        node = pending.pop()
        for neighbor in adjacency.get(node, set()):
            if neighbor in group_nodes and neighbor not in visited:
                visited.add(neighbor)
                pending.append(neighbor)
    return visited == group_nodes


def build_group_edge_updates(
    adjacency: dict[int, set[int]],
    group_nodes: set[int],
    boundary_nodes: set[int],
) -> tuple[dict[str, int], int, int]:
    """Create edge labels equivalent to saving every group member individually.

    Every internal group edge is same-grain (0). Every edge from the group to
    an external node is 1 when that external node is selected as boundary and
    otherwise 0. Counts report unique internal and outgoing edges.
    """
    updates: dict[str, int] = {}
    internal_edges: set[str] = set()
    outgoing_edges: set[str] = set()
    for node in group_nodes:
        for neighbor in adjacency.get(node, set()):
            edge = Edge.from_nodes(node, neighbor)
            if neighbor in group_nodes:
                updates[edge.key] = 0
                internal_edges.add(edge.key)
            else:
                updates[edge.key] = 1 if neighbor in boundary_nodes else 0
                outgoing_edges.add(edge.key)
    return updates, len(internal_edges), len(outgoing_edges)


def load_state(state_path: Path) -> tuple[dict[str, int], set[int]]:
    if not state_path.exists():
        return {}, set()

    with state_path.open("r", encoding="utf-8") as file:
        state = json.load(file)

    edge_labels = {str(key): int(value) for key, value in state.get("edge_labels", {}).items()}
    completed_nodes = {int(node) for node in state.get("completed_nodes", [])}
    return edge_labels, completed_nodes


def save_state(
    state_path: Path,
    csv_path: Path,
    edge_labels: dict[str, int],
    completed_nodes: set[int],
) -> None:
    state_path.parent.mkdir(parents=True, exist_ok=True)

    state = {
        "edge_labels": dict(sorted(edge_labels.items())),
        "completed_nodes": sorted(int(node) for node in completed_nodes),
    }
    state_temp_path = state_path.with_suffix(state_path.suffix + ".tmp")
    csv_temp_path = csv_path.with_suffix(csv_path.suffix + ".tmp")
    with state_temp_path.open("w", encoding="utf-8") as file:
        json.dump(state, file, ensure_ascii=False, indent=2)

    with csv_temp_path.open("w", newline="", encoding="utf-8") as file:
        writer = csv.writer(file)
        writer.writerow(["node_a", "node_b", "edge_label"])
        for key, label in sorted(edge_labels.items(), key=lambda item: tuple(map(int, item[0].split("-")))):
            node_a, node_b = key.split("-")
            writer.writerow([int(node_a), int(node_b), int(label)])
    state_temp_path.replace(state_path)
    csv_temp_path.replace(csv_path)


