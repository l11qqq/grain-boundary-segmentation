@dataclass(frozen=True)
class Edge:
    a: int
    b: int

    @classmethod
    def from_nodes(cls, node_a: int, node_b: int) -> "Edge":
        low, high = sorted((int(node_a), int(node_b)))
        return cls(low, high)

    @property
    def key(self) -> str:
        return f"{self.a}-{self.b}"


def toggle_edge_label(value: int) -> int:
    """Toggle an edge label between same-grain 0 and boundary 1."""
    return 0 if int(value) == 1 else 1


