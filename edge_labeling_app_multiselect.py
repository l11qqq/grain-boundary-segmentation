"""文档简介：
本脚本是 edge_labeling_app.py 的多选副本，用于为后续 GNN 边分类准备监督标签。
Usage example / 调用示例：
    python slic_test.py
    python edge_labeling_app_multiselect.py --data-dir outputs/slic_1
界面左右两侧都展示标准差图：左侧用于查看超像素边界，右侧用于交互标注。
用户点击一个超像素作为中心节点后，中心节点高亮，邻接节点变色提示，右侧显示邻接节点 checkbox 列表。
checkbox 勾选表示该邻接边属于不同晶粒，标签为 1；未勾选表示同一晶粒，标签为 0。
标注结果持续保存为 JSON 和 CSV；下次打开会自动恢复已标注边和已完成中心节点，支持继续标注或修改旧标签。
每个 SLIC 数据目录是独立会话：例如读取 outputs/slic_1 时，标签保存到
outputs/slic_1/edge_labels；可通过界面按钮切换到 slic_2 等目录。

多选工作流：
1. 切换到“多选晶粒”，从一个超像素开始，逐步点击当前集团的相邻超像素。
2. 集团覆盖完整晶粒后切换到“标记外圈”，将外圈节点标为不同晶粒（支持一键全选）。
3. 点击“保存整个晶粒”。集团内部边写为 0，集团到外圈的边按选择写为 1/0，
   集团内所有超像素一次性记为已完成；输出 JSON/CSV 与原单选模式完全兼容。
"""

