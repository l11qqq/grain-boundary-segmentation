    @staticmethod
    def _resolve_data_file(data_dir: Path, key: str, default_name: str) -> Path:
        config_path = data_dir / "labeling_config.json"
        configured_name = default_name
        if config_path.is_file():
            try:
                config = json.loads(config_path.read_text(encoding="utf-8"))
                if isinstance(config, dict) and isinstance(config.get(key), str):
                    configured_name = config[key]
            except (OSError, json.JSONDecodeError):
                # The standard filenames remain usable if optional metadata is malformed.
                pass
        path = Path(configured_name)
        return path.resolve() if path.is_absolute() else (data_dir / path).resolve()

    def _read_data_dir(self, data_dir: Path) -> dict[str, object]:
        data_dir = data_dir.resolve()
        if not data_dir.is_dir():
            raise FileNotFoundError(f"数据目录不存在：{data_dir}")

        label_map_path = self._resolve_data_file(data_dir, "label_map", "slic_labels.npy")
        std_image_path = self._resolve_data_file(data_dir, "std_image", "std_image.png")
        if not std_image_path.is_file():
            legacy_std_path = self._resolve_data_file(data_dir, "slop_image", "slop_image.png")
            if legacy_std_path.is_file():
                std_image_path = legacy_std_path
        missing = [path for path in (label_map_path, std_image_path) if not path.is_file()]
        if missing:
            missing_text = "\n".join(f"  - {path}" for path in missing)
            raise FileNotFoundError(f"数据目录缺少必要文件：\n{missing_text}")

        labels = np.asarray(np.load(label_map_path, allow_pickle=False), dtype=np.int32)
        if labels.ndim != 2:
            raise ValueError(f"label_map must be 2D, got {labels.shape}")
        std_image = Image.open(std_image_path).convert("RGB")
        expected_size = (labels.shape[1], labels.shape[0])
        if std_image.size != expected_size:
            std_image.close()
            raise ValueError(f"std image size {std_image.size} does not match label_map {expected_size}")

        output_dir = data_dir / "edge_labels"
        state_path = output_dir / "edge_labels.json"
        csv_path = output_dir / "edge_labels.csv"
        edge_labels, completed_nodes = load_state(state_path)
        return {
            "data_dir": data_dir,
            "label_map_path": label_map_path,
            "std_image_path": std_image_path,
            "output_dir": output_dir,
            "state_path": state_path,
            "csv_path": csv_path,
            "labels": labels,
            "std_image": std_image,
            "edge_labels": edge_labels,
            "completed_nodes": completed_nodes,
        }

    def save_current_progress(self) -> None:
        if self.data_dir is None or self.state_path is None or self.csv_path is None:
            return
        if self.selected_node is not None:
            for neighbor, var in self.neighbor_vars.items():
                edge = Edge.from_nodes(self.selected_node, neighbor)
                self.edge_labels[edge.key] = int(var.get())
        save_state(self.state_path, self.csv_path, self.edge_labels, self.completed_nodes)

    def load_data_dir(self, data_dir: Path, save_before_switch: bool = True) -> None:
        loaded = self._read_data_dir(Path(data_dir))
        if save_before_switch:
            self.save_current_progress()
        if self.std_image is not None:
            self.std_image.close()

        self.data_dir = loaded["data_dir"]
        self.label_map_path = loaded["label_map_path"]
        self.std_image_path = loaded["std_image_path"]
        self.output_dir = loaded["output_dir"]
        self.state_path = loaded["state_path"]
        self.csv_path = loaded["csv_path"]
        self.labels = loaded["labels"]
        self.std_image = loaded["std_image"]
        self.boundaries = compute_boundaries(self.labels)
        self.detail_base = np.asarray(self.std_image, dtype=np.uint8).copy()
        self.overview_base = self.detail_base.copy()
        self.adjacency = build_adjacency(self.labels)
        self.label_ids = sorted(self.adjacency)
        self.edge_labels = loaded["edge_labels"]
        self.completed_nodes = loaded["completed_nodes"]
        self.selected_node = None
        self.neighbor_vars.clear()
        self.selected_group.clear()
        self.group_boundary_nodes.clear()
        self.group_boundary_vars.clear()
        self.interaction_mode.set(MODE_SINGLE)
        self.data_dir_var.set(str(self.data_dir))
        self.root.title(f"Superpixel Edge Labeling - Multi-select - {self.data_dir.name}")
        self.select_first_uncompleted()

    def choose_data_directory(self) -> None:
        initial_dir = str(self.data_dir.parent if self.data_dir is not None else DEFAULT_SLIC_OUTPUT_DIR)
        selected = filedialog.askdirectory(
            parent=self.root,
            title="选择SLIC数据目录",
            initialdir=initial_dir,
            mustexist=True,
        )
        if not selected:
            return
        selected_path = Path(selected).resolve()
        if self.data_dir is not None and selected_path == self.data_dir:
            return
        if self.selected_group:
            discard = messagebox.askyesno(
                "多选晶粒尚未保存",
                f"当前还有 {len(self.selected_group)} 个已选超像素尚未批量保存。"
                "\n切换数据目录将丢弃这次临时选择，是否继续？",
                parent=self.root,
            )
            if not discard:
                return
        try:
            self.load_data_dir(selected_path)
        except Exception as error:
            messagebox.showerror("读取数据目录失败", str(error), parent=self.root)

